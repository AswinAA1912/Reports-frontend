export interface TripDetail {
  tripId: string;
  vehicleNo: string;
  driverName: string;
  driverPhone: string;
  transporter: string;
  lrNo: string;
  dispatchDate: string;
  deliveryDate?: string;
  status: "Delivered" | "In Transit" | "Unloaded" | "Dispatched" | "Pending";
  destinationGodown: string;
  loadingPoint: string;
}

export type DeliveryStatus =
  | "Arrived Today"
  | "Arrived Earlier"
  | "Not Delivered"
  | "In Transit"
  | "Pending Delivery";

export type PaymentStatus = "Paid" | "Partial" | "Unpaid";

export interface OrderItemDetail {
  id: string;
  itemNo: number;
  itemName: string;
  qty: string;
  tonnage: number;
  rate: number;
  itemValue: number;
  arrivalDate: string;
  status: DeliveryStatus;
  tripDetail?: TripDetail;
}

export interface WholeOrderDetails {
  orderId: string;
  orderDate: string;
  retailerName: string;
  city: string;
  state: string;
  totalOrderTonnage: number;
  totalOrderValue: number;
  paymentStatus: PaymentStatus;
  paidAmount: number;
  balanceAmount: number;
  items: OrderItemDetail[];
}

