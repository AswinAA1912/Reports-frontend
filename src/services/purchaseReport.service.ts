export const getPurchaseDataByFilter = (
  filterType: PurchaseReportFilterType
): TodayArrivalItem[] => {
  switch (filterType) {
    case "today_arrival":
      return DUMMY_PURCHASE_DATA;
    case "pending_orders":
      return DUMMY_PENDING_ORDERS_DATA;
    case "pending_payments":
      return DUMMY_PENDING_PAYMENTS_DATA;
    case "completed":
      return DUMMY_COMPLETED_DATA;
    default:
      return DUMMY_PURCHASE_DATA;
  }
};

export const getPurchaseFilterCounts = () => ({
  today_arrival: DUMMY_PURCHASE_DATA.length,
  pending_orders: DUMMY_PENDING_ORDERS_DATA.length,
  pending_payments: DUMMY_PENDING_PAYMENTS_DATA.length,
  completed: DUMMY_COMPLETED_DATA.length,
});

export const PurchaseReportService = {
  getPurchaseReportData: async (params?: {
    fromDate?: string;
    toDate?: string;
    partyName?: string;
    filterType?: PurchaseReportFilterType;
  }): Promise<{ success: boolean; data: TodayArrivalItem[] }> => {
    await new Promise((resolve) => setTimeout(resolve, 200));

    const baseData = getPurchaseDataByFilter(params?.filterType || "today_arrival");
    let filtered = [...baseData];

    if (params?.fromDate && params?.toDate) {
      const from = dayjs(params.fromDate);
      const to = dayjs(params.toDate);
      if (from.isValid() && to.isValid()) {
        filtered = filtered.filter((row) => {
          const parts = row.date.split("/");
          if (parts.length === 3) {
            const rowDate = dayjs(`${parts[2]}-${parts[1]}-${parts[0]}`);
            return (
              (rowDate.isAfter(from) || rowDate.isSame(from, "day")) &&
              (rowDate.isBefore(to) || rowDate.isSame(to, "day"))
            );
          }
          return true;
        });
      }
    }

    if (params?.partyName) {
      const term = params.partyName.toLowerCase();
      filtered = filtered.filter(
        (row) =>
          row.retailerName.toLowerCase().includes(term) ||
          row.itemName.toLowerCase().includes(term) ||
          row.orderId.toLowerCase().includes(term) ||
          row.city.toLowerCase().includes(term)
      );
    }

    return {
      success: true,
      data: filtered,
    };
  },
};
